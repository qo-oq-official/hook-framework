param(
    [string]$OutFile = "test_scale_target.cpp",
    [int]$FillerCount = 508,
    [int]$RvaFnCount = 12
)

$lines = @()
$lines += '// Auto-generated by gen_scale_target.ps1'
$lines += '#include <cstdint>'
$lines += '#include <cstdio>'
$lines += ''
$lines += '#ifdef TEST_SCALE_EXPORTS'
$lines += '#define EXPORT __declspec(dllexport)'
$lines += '#else'
$lines += '#define EXPORT __declspec(dllimport)'
$lines += '#endif'
$lines += ''
$lines += '// --- Filler noop exports (for trace hooks) ---'
for ($i = 0; $i -lt $FillerCount; $i++) {
    $name = "test_n{0:D4}" -f $i
    $lines += "extern `"C`" EXPORT __declspec(noinline) void $name();"
}
$lines += ''
$lines += '// --- RVA target functions ---'
for ($i = 0; $i -lt $RvaFnCount; $i++) {
    $name = "test_rva_fn_$i"
    $lines += "extern `"C`" EXPORT __declspec(noinline) int $name(int a);"
}
$lines += ''
$lines += '// ======== IMPLEMENTATIONS ========'
$lines += ''
for ($i = 0; $i -lt $FillerCount; $i++) {
    $name = "test_n{0:D4}" -f $i
    $lines += "void $name() {"
    $lines += "    volatile int keep = $i;"
    $lines += "    (void)keep;"
    $lines += "}"
}
$lines += ''
for ($i = 0; $i -lt $RvaFnCount; $i++) {
    $name = "test_rva_fn_$i"
    $lines += "extern `"C`" int $name(int a) {"
    $lines += "    return a * ($i + 1);"
    $lines += "}"
}

$content = $lines -join "`r`n"
Set-Content -Path $OutFile -Value $content -Encoding UTF8
Write-Output "Generated ${OutFile}: $($lines.Count) lines, $FillerCount filler + $RvaFnCount rva functions"
